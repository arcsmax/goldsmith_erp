#!/usr/bin/env node
// Generate frontend API types from the backend's OpenAPI document (FE-12, W3-02).
//
//   node scripts/gen-api-types.mjs          regenerate openapi.json + src/api/generated/*
//   node scripts/gen-api-types.mjs --check  regenerate, then fail if anything drifted
//
// The OpenAPI document is exported by importing the FastAPI app directly, so no
// server, database or Redis is needed. Python is `$PYTHON` if set, else
// `poetry run python` from the repo root. See docs/technical/FRONTEND_API_TYPES.md.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const FRONTEND_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = resolve(FRONTEND_DIR, '..');
const OPENAPI_PATH = join(FRONTEND_DIR, 'openapi.json');
const GENERATED_DIR = join(FRONTEND_DIR, 'src', 'api', 'generated');
const SCHEMA_PATH = join(GENERATED_DIR, 'schema.d.ts');
const ENUMS_PATH = join(GENERATED_DIR, 'enums.json');
const CHECKED_PATHS = ['frontend/openapi.json', 'frontend/src/api/generated'];

// Import-time settings validation needs these. They are the same throwaway
// values CI uses (.github/workflows/ci.yml); the schema does not depend on them.
const EXPORT_ENV_DEFAULTS = {
  SECRET_KEY: 'ci-test-secret-key-minimum-32-characters-long-enough',
  ENCRYPTION_KEY: 'V0Ae_U1MhSkUCNugAmmQV7Jl2GnxkizHeurQnglXVOc=',
  ANONYMIZATION_SALT: 'testsalt1234567890abcdef',
  DEBUG: 'true',
};

const BANNER =
  '// AUTO-GENERATED by frontend/scripts/gen-api-types.mjs from the backend OpenAPI schema.\n' +
  '// Do not edit by hand: change the Pydantic schema, then run `make types`.\n\n';

// main.py logs to stdout, so the document is written to a file (argv[1]).
const EXPORT_SNIPPET = [
  'import json, sys',
  'from goldsmith_erp.main import app',
  'with open(sys.argv[1], "w", encoding="utf-8") as fh:',
  '    json.dump(app.openapi(), fh, indent=2, ensure_ascii=False)',
  '    fh.write("\\n")',
].join('\n');

function fail(message) {
  console.error(`gen-api-types: ${message}`);
  process.exit(1);
}

function pythonCommand() {
  if (process.env.PYTHON) return { cmd: process.env.PYTHON, args: [] };
  return { cmd: 'poetry', args: ['run', 'python'] };
}

function exportOpenApi() {
  // Run in a scratch cwd: main.py creates ./uploads at import time.
  const scratch = mkdtempSync(join(tmpdir(), 'gen-api-types-'));
  try {
    const { cmd, args } = pythonCommand();
    const env = {
      ...EXPORT_ENV_DEFAULTS,
      ...process.env,
      PYTHONPATH: join(REPO_ROOT, 'src'),
      PHOTO_STORAGE_PATH: join(scratch, 'uploads', 'photos'),
    };
    const result = spawnSync(cmd, [...args, '-c', EXPORT_SNIPPET, OPENAPI_PATH], {
      cwd: cmd === 'poetry' ? REPO_ROOT : scratch,
      env,
      stdio: ['ignore', 'ignore', 'inherit'],
    });
    if (result.error) fail(`could not run ${cmd}: ${result.error.message}`);
    if (result.status !== 0) fail(`OpenAPI export exited with ${result.status}`);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  return JSON.parse(readFileSync(OPENAPI_PATH, 'utf-8'));
}

function collectEnums(document) {
  const schemas = document.components?.schemas ?? {};
  const enums = {};
  for (const name of Object.keys(schemas).sort()) {
    const values = schemas[name].enum;
    if (Array.isArray(values)) enums[name] = values;
  }
  return enums;
}

async function generate() {
  const document = exportOpenApi();
  const ast = await openapiTS(document, { alphabetize: true });
  mkdirSync(GENERATED_DIR, { recursive: true });
  writeFileSync(SCHEMA_PATH, BANNER + astToString(ast));
  writeFileSync(ENUMS_PATH, JSON.stringify(collectEnums(document), null, 2) + '\n');
  console.log(`gen-api-types: wrote ${Object.keys(document.components?.schemas ?? {}).length} schemas`);
}

function checkDrift() {
  const diff = spawnSync('git', ['diff', '--exit-code', '--stat', '--', ...CHECKED_PATHS], {
    cwd: REPO_ROOT,
    stdio: 'inherit',
  });
  const untracked = spawnSync(
    'git',
    ['ls-files', '--others', '--exclude-standard', '--', ...CHECKED_PATHS],
    { cwd: REPO_ROOT, encoding: 'utf-8' },
  );
  if (diff.status !== 0 || untracked.stdout.trim() !== '') {
    fail(
      'generated API types are out of date with the backend schema.\n' +
        'Run `make types` (or `node frontend/scripts/gen-api-types.mjs`) and commit the result.',
    );
  }
  console.log('gen-api-types: generated types match the backend schema');
}

await generate();
if (process.argv.includes('--check')) checkDrift();
